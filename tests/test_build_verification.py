"""The release gate must reject failures and bind receipts to the tested inputs."""

import importlib.util
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest


SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "verify_build.py"


def load_gate():
    assert SCRIPT.is_file(), "the build verification gate has not been implemented"
    spec = importlib.util.spec_from_file_location("verify_build", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_receipt_counts_actual_testcases_and_records_explicit_skips(tmp_path):
    gate = load_gate()
    report = tmp_path / "junit.xml"
    report.write_text(
        '<testsuites><testsuite tests="3" failures="0" errors="0" skipped="1">'
        '<testcase classname="checks" name="one" />'
        '<testcase classname="checks" name="two" />'
        '<testcase classname="checks" name="database"><skipped '
        'message="TEST_DATABASE_URL not set; actual PostgreSQL required" />'
        "</testcase></testsuite></testsuites>"
    )
    result = gate.read_junit(report)
    assert result["total"] == 3
    assert result["passed"] == 2
    assert result["skipped"] == 1
    assert result["failures"] == result["errors"] == 0
    assert result["skips"] == [
        {
            "test": "checks.database",
            "reason": "TEST_DATABASE_URL not set; actual PostgreSQL required",
        }
    ]


@pytest.mark.parametrize(
    "body",
    [
        '<testsuites><testsuite tests="0" /></testsuites>',
        '<testsuite tests="1"><testcase><failure /></testcase></testsuite>',
        '<testsuite tests="1"><testcase><error /></testcase></testsuite>',
        '<testsuite tests="1"><testcase><skipped /></testcase></testsuite>',
        '<testsuite tests="2"><testcase /></testsuite>',
    ],
)
def test_empty_failing_all_skipped_and_inconsistent_reports_cannot_pass(tmp_path, body):
    gate = load_gate()
    report = tmp_path / "junit.xml"
    report.write_text(body)
    with pytest.raises(ValueError):
        gate.read_junit(report)


def test_fingerprint_ignores_generated_metadata_and_cache_files(tmp_path):
    gate = load_gate()
    source = tmp_path / "src"
    source.mkdir()
    (source / "sample.py").write_text("VALUE = 1\n")
    original = gate.fingerprint(tmp_path, [source])
    metadata = source / "sample.egg-info"
    metadata.mkdir()
    (metadata / "PKG-INFO").write_text("generated packaging metadata")
    cache = source / "__pycache__"
    cache.mkdir()
    (cache / "sample.pyc").write_bytes(b"generated bytecode")
    assert gate.fingerprint(tmp_path, [source]) == original


def fixture_project(tmp_path, body):
    (tmp_path / "src").mkdir()
    (tmp_path / "tests").mkdir()
    (tmp_path / "src" / "sample.py").write_text("VALUE = 1\n")
    (tmp_path / "tests" / "test_sample.py").write_text(body)
    (tmp_path / "requirements.lock").write_text("example==1.0\n")
    (tmp_path / "requirements-test.lock").write_text("pytest==8.4.2\n")
    (tmp_path / "pyproject.toml").write_text('[tool.pytest.ini_options]\ntestpaths=["tests"]\n')
    assert SCRIPT.is_file(), "the build verification gate has not been implemented"
    (tmp_path / "scripts").mkdir()
    shutil.copyfile(SCRIPT, tmp_path / "scripts" / "verify_build.py")
    return tmp_path / "receipt.json"


def run_fixture(root, receipt):
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root), "--output", str(receipt)],
        capture_output=True,
        text=True,
        timeout=60,
    )


def test_real_failing_test_blocks_release_and_removes_stale_receipt(tmp_path):
    receipt = fixture_project(tmp_path, "def test_failure():\n    assert False\n")
    receipt.write_text('{"status":"passed"}')
    result = run_fixture(tmp_path, receipt)
    assert result.returncode != 0
    assert "1 failed" in result.stdout
    assert not receipt.exists()


def test_real_lint_failure_blocks_release(tmp_path):
    receipt = fixture_project(tmp_path, "def test_ok():\n    assert True\n")
    (tmp_path / "src" / "sample.py").write_text("import unused_dependency\n")
    result = run_fixture(tmp_path, receipt)
    assert result.returncode != 0
    assert "F401" in result.stdout
    assert not receipt.exists()


def test_success_receipt_is_fingerprinted_and_tests_receive_no_provider_credentials(
    tmp_path, monkeypatch
):
    receipt = fixture_project(
        tmp_path,
        "import os\n\ndef test_environment():\n"
        '    assert "OPENAI_API_KEY" not in os.environ\n'
        '    assert "TEST_DATABASE_URL" not in os.environ\n',
    )
    monkeypatch.setenv("OPENAI_API_KEY", "must-never-reach-tests")
    monkeypatch.setenv("TEST_DATABASE_URL", "must-never-reach-tests")
    first = run_fixture(tmp_path, receipt)
    assert first.returncode == 0, first.stdout + first.stderr
    result = json.loads(receipt.read_text())
    assert result["status"] == "passed"
    assert result["pytest"]["passed"] == 1
    assert result["pytest"]["skipped"] == 0
    assert "must-never-reach-tests" not in receipt.read_text()
    original = result["fingerprints"]
    (tmp_path / "src" / "sample.py").write_text("VALUE = 2\n")
    second = run_fixture(tmp_path, receipt)
    assert second.returncode == 0, second.stdout + second.stderr
    changed = json.loads(receipt.read_text())["fingerprints"]
    assert changed["source"] != original["source"]
    assert changed["tests"] == original["tests"]
    assert changed["locks"] == original["locks"]
